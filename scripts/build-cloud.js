const fs = require('node:fs');
const path = require('node:path');
const { buildSync } = require('esbuild');
const root = path.resolve(__dirname, '..');
const functionDir = path.join(root, 'cloudfunctions/peakLifeApi');

// Keep local modules and JSON inside the entry point so Windows ZIP path
// separators cannot break require() when the package is extracted on Linux.
buildSync({
  absWorkingDir: root,
  entryPoints: ['cloudfunctions/peakLifeApi/main.js'],
  outfile: path.join(functionDir, 'index.js'),
  bundle: true,
  platform: 'node',
  format: 'cjs',
  target: 'node16.13',
  external: ['wx-server-sdk'],
  banner: { js: '// Generated by npm run build:cloud. Edit main.js and lib/, then rebuild.' },
  logLevel: 'info'
});
const output = fs.readFileSync(path.join(functionDir, 'index.js'), 'utf8');
if (/\brequire\(["']\.\.?\//.test(output)) throw new Error('Cloud bundle still contains relative runtime imports');
